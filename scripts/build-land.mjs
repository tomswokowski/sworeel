// Writes plugin/core/data/land.ts: the outline of the world's land at low detail, for the map
// kind. Run: node scripts/build-land.mjs
import { readFileSync, writeFileSync } from 'node:fs'
import { feature } from 'topojson-client'

const world = JSON.parse(readFileSync('node_modules/world-atlas/land-110m.json', 'utf8'))
const land = feature(world, world.objects.land)

// Each ring becomes a flat list: longitude, latitude, longitude, latitude, to one decimal place.
const rings = []
for (const geometry of land.features ?? [land]) {
  const polygons = geometry.geometry.type === 'Polygon' ? [geometry.geometry.coordinates] : geometry.geometry.coordinates
  for (const polygon of polygons) {
    // Only the outer boundary: the few lakes this drops are too small to see at this size.
    const points = polygon[0].map(([lon, lat]) => [Math.round(lon * 10) / 10, Math.round(lat * 10) / 10])
    if (points.length < 4) continue
    // Antarctica is closed along the pole, which is right as it stands.
    if (Math.min(...points.map(([, lat]) => lat)) < -85) {
      rings.push(points.flat())
      continue
    }
    // A coastline that crosses the date line jumps from 180 to -180. Unwrap it into one
    // continuous outline, then give a second copy a full turn away, so both sides are there.
    let turn = 0
    const unwrapped = points.map(([lon, lat], i) => {
      if (i > 0 && Math.abs(lon - points[i - 1][0]) > 180) turn += lon < points[i - 1][0] ? 360 : -360
      return [Math.round((lon + turn) * 10) / 10, lat]
    })
    const lons = unwrapped.map(([lon]) => lon)
    rings.push(unwrapped.flat())
    if (Math.max(...lons) > 180) rings.push(unwrapped.flatMap(([lon, lat]) => [Math.round((lon - 360) * 10) / 10, lat]))
    if (Math.min(...lons) < -180) rings.push(unwrapped.flatMap(([lon, lat]) => [Math.round((lon + 360) * 10) / 10, lat]))
  }
}

// Ten points to a line, so the file reads as data and not as one minified line.
const wrap = (ring) => {
  const lines = []
  for (let i = 0; i < ring.length; i += 20) lines.push(`    ${ring.slice(i, i + 20).join(', ')},`)
  return `  [\n${lines.join('\n')}\n  ],`
}

writeFileSync(
  'plugin/core/data/land.ts',
  `// Generated by scripts/build-land.mjs. Do not edit by hand.
//
// Land outlines from Natural Earth (public domain), 1:110m, via the world-atlas package.
// Each ring is a flat list of longitude, latitude pairs.

export const LAND: number[][] = [
${rings.map(wrap).join('\n')}
]
`,
)
console.log(`${rings.length} rings, ${rings.reduce((n, ring) => n + ring.length / 2, 0)} points`)
