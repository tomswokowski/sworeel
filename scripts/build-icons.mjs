// Writes plugin/core/data/icons.ts: a chosen set of Lucide icons, each reduced to SVG path
// strings so the renderer needs nothing but a path to stroke. Run: node scripts/build-icons.mjs
import { readFileSync, writeFileSync } from 'node:fs'

const NAMES = `
server database hard-drive cpu cloud globe network router wifi cable plug container box package layers
monitor laptop smartphone terminal code file folder image
user users bot brain building store house
lock key shield eye bug
mail message-square bell webhook link
shopping-cart credit-card truck tag
clock timer calendar gauge activity chart-bar zap rocket flag
search settings funnel list workflow git-branch refresh-cw
check x triangle-alert info star heart
play pause download upload trash pencil arrow-right map-pin book camera
`.trim().split(/\s+/)

const nodes = JSON.parse(readFileSync('node_modules/lucide-static/icon-nodes.json', 'utf8'))
const n = (value) => Number(value ?? 0)

/** One SVG shape as a path string. */
function toPath([tag, a]) {
  switch (tag) {
    case 'path':
      return a.d
    case 'line':
      return `M${a.x1} ${a.y1}L${a.x2} ${a.y2}`
    case 'polyline':
    case 'polygon':
      return `M${a.points.trim().split(/\s+/).join('L')}${tag === 'polygon' ? 'Z' : ''}`
    case 'circle':
    case 'ellipse': {
      const [rx, ry] = tag === 'circle' ? [n(a.r), n(a.r)] : [n(a.rx), n(a.ry)]
      return `M${n(a.cx) - rx} ${a.cy}a${rx} ${ry} 0 1 0 ${rx * 2} 0a${rx} ${ry} 0 1 0 ${-rx * 2} 0`
    }
    case 'rect': {
      const [x, y, w, h] = [n(a.x), n(a.y), n(a.width), n(a.height)]
      const r = Math.min(n(a.rx ?? a.ry), w / 2, h / 2)
      if (!r) return `M${x} ${y}h${w}v${h}h${-w}Z`
      return `M${x + r} ${y}h${w - 2 * r}a${r} ${r} 0 0 1 ${r} ${r}v${h - 2 * r}a${r} ${r} 0 0 1 ${-r} ${r}h${2 * r - w}a${r} ${r} 0 0 1 ${-r} ${-r}v${2 * r - h}a${r} ${r} 0 0 1 ${r} ${-r}Z`
    }
    default:
      throw new Error(`Unhandled SVG element <${tag}>`)
  }
}

const icons = Object.fromEntries(
  NAMES.map((name) => {
    if (!nodes[name]) throw new Error(`Lucide has no icon called "${name}"`)
    return [name, nodes[name].map(toPath)]
  }),
)

writeFileSync(
  'plugin/core/data/icons.ts',
  `// Generated by scripts/build-icons.mjs. Do not edit by hand.
//
// Icons from Lucide (https://lucide.dev), ISC License,
// Copyright (c) Lucide Icons and Contributors.
//
// Each icon is drawn on a 24 by 24 grid by stroking these paths, 2 wide, with round ends.

export const ICONS: Record<string, string[]> = ${JSON.stringify(icons, null, 2)}

export const ICON_NAMES = Object.keys(ICONS)
`,
)
console.log(`${NAMES.length} icons written`)
